SELECT * FROM MODALIDADE;
 
SELECT
    MODALIDADE.NOME AS "MODALIDADE",
    INSTRUTOR.NOME AS "INSTRUTOR",
    AULA.DIA_SEMANA AS "DIA DA SEMANA",
    AULA.DURACAO_MIN AS "DURAÇÃO (MIN)"
FROM AULA
JOIN MODALIDADE ON AULA.FK_MODALIDADE = MODALIDADE.IDMODALIDADE
JOIN INSTRUTOR ON AULA.FK_INSTRUTOR = INSTRUTOR.IDINSTRUTOR;
 
SELECT
    ALUNO.NOME AS "NOME DO ALUNO",
    COUNT(MATRICULA.FK_MODALIDADE) AS "QUANTIDADE DE MODALIDADES"
FROM ALUNO
LEFT JOIN MATRICULA ON MATRICULA.FK_ALUNO = ALUNO.IDALUNO
GROUP BY ALUNO.IDALUNO, ALUNO.NOME;
 
SELECT
    INSTRUTOR.NOME AS "INSTRUTOR",
    COUNT(DISTINCT AULA.FK_MODALIDADE) AS "MODALIDADES DIFERENTES",
    ROUND(AVG(AULA.DURACAO_MIN), 1) AS "DURAÇÃO MÉDIA (MIN)"
FROM INSTRUTOR
JOIN AULA ON AULA.FK_INSTRUTOR = INSTRUTOR.IDINSTRUTOR
GROUP BY INSTRUTOR.IDINSTRUTOR, INSTRUTOR.NOME;
 
SELECT
    MODALIDADE.NOME AS "MODALIDADE",
    COUNT(DISTINCT MATRICULA.FK_ALUNO) AS "ALUNOS MATRICULADOS",
    COUNT(DISTINCT AULA.FK_INSTRUTOR) AS "INSTRUTORES DIFERENTES"
FROM MODALIDADE
JOIN MATRICULA ON MATRICULA.FK_MODALIDADE = MODALIDADE.IDMODALIDADE
LEFT JOIN AULA ON AULA.FK_MODALIDADE = MODALIDADE.IDMODALIDADE
GROUP BY MODALIDADE.IDMODALIDADE, MODALIDADE.NOME
HAVING COUNT(DISTINCT MATRICULA.FK_ALUNO) > 3;
 
SELECT
    INSTRUTOR.NOME AS "INSTRUTOR",
    COUNT(AULA.IDAULA) AS "AULAS SEMANAIS",
    COUNT(AULA.IDAULA) * INSTRUTOR.VALOR_P_AULA AS "TOTAL SEMANAL (R$)"
FROM INSTRUTOR
LEFT JOIN AULA ON AULA.FK_INSTRUTOR = INSTRUTOR.IDINSTRUTOR
GROUP BY INSTRUTOR.IDINSTRUTOR, INSTRUTOR.NOME, INSTRUTOR.VALOR_P_AULA;