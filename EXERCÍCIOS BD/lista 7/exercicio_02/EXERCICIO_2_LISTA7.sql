SELECT 
	FUNCIONARIO.NOME AS 'FUNCIONÁRIO',
    DEPARTAMENTO.NOME_DEPARTAMENTO AS 'DEPARTEMENTO'
FROM FUNCIONARIO 
JOIN DEPARTAMENTO ON FUNCIONARIO.FK_DEPARTAMENTO = DEPARTAMENTO.ID_DEPARTAMENTO;


SELECT 
		FUNCIONARIO.NOME AS "NOME DO FUNCINÁRIO",
        FUNCIONARIO.SALARIO AS "SALÁRIO",
        FUNCIONARIO.DATA_EMI AS "DATA DE EMISSÃO"
FROM FUNCIONARIO JOIN DEPARTAMENTO ON FUNCIONARIO.FK_DEPARTAMENTO = DEPARTAMENTO.ID_DEPARTAMENTO
WHERE FUNCIONARIO.DATA_EMI > "2018-01-01";

SELECT
	FUNCIONARIO.NOME AS "NOME FUNCIONÁRIO",
    DEPARTAMENTO.NOME_DEPARTAMENTO AS "DEPARTAMENTO"
FROM FUNCIONARIO JOIN DEPARTAMENTO ON FUNCIONARIO.FK_DEPARTAMENTO = DEPARTAMENTO.ID_DEPARTAMENTO AND DEPARTAMENTO.ID_DEPARTAMENTO IN (2,3);

SELECT
		FUNCIONARIO.NOME AS "NOME DO FUNCIONÁRIO",
        FUNCIONARIO.SALARIO AS "SALÁRIO"
FROM FUNCIONARIO JOIN DEPARTAMENTO ON FUNCIONARIO.FK_DEPARTAMENTO = DEPARTAMENTO.ID_DEPARTAMENTO
ORDER BY FUNCIONARIO.SALARIO DESC;



SELECT 
    SUPERVISOR.NOME AS "SUPERVISOR",
    SUBORDINADO.NOME AS "SUBORDINADO"
FROM FUNCIONARIO AS SUBORDINADO JOIN FUNCIONARIO AS SUPERVISOR ON SUBORDINADO.FK_SUPERVISOR = SUPERVISOR.ID_FUNCIONARIO;

SELECT 
	FUNC.NOME AS "NOME FUNCIONARIO",
    SUPE.NOME AS "SSUPERVISOR"
FROM FUNCIONARIO AS FUNC JOIN FUNCIONARIO AS SUPE ON FUNC.FK_SUPERVISOR= SUPE.ID_FUNCIONARIO
WHERE SUPE.NOME LIKE "A%";

SELECT 
	FUNC.NOME AS "NOME FUNCIONARIO",
    SUPE.NOME AS "SUPERVISOR",
    FUNC.SALARIO AS "SALARIO",
    CASE 
		WHEN FUNC.SALARIO <= 3000 THEN "SALÁRIO MÉDIO"
        WHEN FUNC.SALARIO >= 3500 THEN "SALÁRIO MÉDIO ALTO"
        WHEN FUNC.SALARIO > 6000 THEN "SALÁRIO ALTO"
    END AS "SALARIO FUNCIONARIO"
FROM FUNCIONARIO AS FUNC JOIN FUNCIONARIO AS SUPE ON FUNC.FK_SUPERVISOR= SUPE.ID_FUNCIONARIO
ORDER BY FUNC.SALARIO ASC;

