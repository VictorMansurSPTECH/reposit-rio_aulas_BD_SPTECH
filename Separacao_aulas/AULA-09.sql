	C.FK_DONO,
    C.ID_CAO ,
    D.NOME AS "NOME DO DONO",
    C.NOME AS "NOME DO CACHORO"
    
FROM DONO AS D
JOIN CAO AS C
ON C.FK_DONO = D.IDDONO;

