CREATE TABLE DONO(
idDono INT PRIMARY KEY,
NOME VARCHAR(45),
CPF CHAR(11)
);

CREATE TABLE CAO(
ID_CAO INT,
NOME VARCHAR(45),
RACA VARCHAR(45),
FK_DONO INT,
CONSTRAINT CK_FK_DONO FOREIGN KEY(FK_DONO) REFERENCES dono(idDono),
CONSTRAINT PK_DONO_CAO PRIMARY KEY (ID_CAO,FK_DONO)
);

