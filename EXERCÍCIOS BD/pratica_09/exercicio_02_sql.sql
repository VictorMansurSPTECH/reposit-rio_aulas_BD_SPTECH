SELECT
    FUNCIONARIO.NOME AS "NOME DO FUNCIONÁRIO",
    EQUIPE.NOME_EQUIPE AS "EQUIPE",
    AREA_ATUACAO.NOME AS "ÁREA DE ATUAÇÃO"
FROM FUNCIONARIO
JOIN EQUIPE ON FUNCIONARIO.FK_EQUIPE = EQUIPE.IDEQUIPE
JOIN AREA_ATUACAO ON EQUIPE.FK_AREA_ATUACAO = AREA_ATUACAO.IDAREA_ATUACAO;

SELECT
    F.NOME AS "FUNCIONÁRIO",
    M.NOME AS "MENTOR"
FROM FUNCIONARIO AS F
JOIN FUNCIONARIO AS M ON F.FK_MENTOR = M.IDFUNCIONARIO;

SELECT
    FUNCIONARIO.NOME AS "NOME DO FUNCIONÁRIO",
    AREA_ATUACAO.NOME AS "ÁREA DE ATUAÇÃO"
FROM FUNCIONARIO
JOIN EQUIPE ON FUNCIONARIO.FK_EQUIPE = EQUIPE.IDEQUIPE
JOIN AREA_ATUACAO ON EQUIPE.FK_AREA_ATUACAO = AREA_ATUACAO.IDAREA_ATUACAO
WHERE AREA_ATUACAO.NOME IN ("Tecnologia", "Marketing");

SELECT
    FUNCIONARIO.NOME AS "NOME DO FUNCIONÁRIO",
    FUNCIONARIO.DATA_ADMIN AS "DATA DE ADMISSÃO",
    EQUIPE.NOME_EQUIPE AS "EQUIPE",
    AREA_ATUACAO.NOME AS "ÁREA DE ATUAÇÃO"
FROM FUNCIONARIO
JOIN EQUIPE ON FUNCIONARIO.FK_EQUIPE = EQUIPE.IDEQUIPE
JOIN AREA_ATUACAO ON EQUIPE.FK_AREA_ATUACAO = AREA_ATUACAO.IDAREA_ATUACAO
WHERE FUNCIONARIO.DATA_ADMIN > '2022-01-01'
ORDER BY FUNCIONARIO.DATA_ADMIN DESC
LIMIT 3;

