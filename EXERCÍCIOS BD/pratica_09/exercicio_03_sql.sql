SELECT DISTINCT
    TURNO.NOME_TURNO AS "TURNO"
FROM TURNO
JOIN TURMA ON TURMA.FK_TURNO = TURNO.IDTURNO;

SELECT
    ALUNO.NOME_ALUNO AS "NOME DO ALUNO",
    ALUNO.RA AS "RA",
    TURMA.CODIGO AS "TURMA",
    CURSO.NOME_CURSO AS "CURSO",
    STATUS_MATRICULA.DESCRICAO AS "STATUS DA MATRÍCULA"
FROM ALUNO
JOIN TURMA ON ALUNO.FK_TURMA = TURMA.IDTURMA
JOIN CURSO ON TURMA.FK_CURSO = CURSO.IDCURSO
JOIN STATUS_MATRICULA ON ALUNO.FK_STATUS = STATUS_MATRICULA.IDSTATUS;

SELECT
    ALUNO.NOME_ALUNO AS "NOME DO ALUNO",
    TURMA.CODIGO AS "TURMA"
FROM ALUNO
JOIN TURMA ON ALUNO.FK_TURMA = TURMA.IDTURMA
JOIN CURSO ON TURMA.FK_CURSO = CURSO.IDCURSO
WHERE CURSO.NOME_CURSO = "Desenvolvimento de Sistemas"
LIMIT 5;

SELECT
    ALUNO.NOME_ALUNO AS "NOME DO ALUNO",
    ALUNO.RA AS "RA",
    STATUS_MATRICULA.DESCRICAO AS "STATUS DA MATRÍCULA"
FROM ALUNO
JOIN STATUS_MATRICULA ON ALUNO.FK_STATUS = STATUS_MATRICULA.IDSTATUS
WHERE STATUS_MATRICULA.DESCRICAO = "Ativo";

SELECT
    CURSO.NOME_CURSO AS "CURSO",
    TURMA.CODIGO AS "TURMA"
FROM CURSO
LEFT JOIN TURMA ON TURMA.FK_CURSO = CURSO.IDCURSO;

SELECT
    TURMA.CODIGO AS "TURMA",
    ALUNO.NOME_ALUNO AS "NOME DO ALUNO"
FROM TURMA
LEFT JOIN ALUNO ON ALUNO.FK_TURMA = TURMA.IDTURMA;

SELECT
    CURSO.NOME_CURSO AS "CURSO",
    TURMA.CODIGO AS "TURMA",
    ALUNO.NOME_ALUNO AS "NOME DO ALUNO"
FROM CURSO
LEFT JOIN TURMA ON TURMA.FK_CURSO = CURSO.IDCURSO
LEFT JOIN ALUNO ON ALUNO.FK_TURMA = TURMA.IDTURMA;

SELECT
    ALUNO.NOME_ALUNO AS "NOME DO ALUNO",
    TURMA.CODIGO AS "TURMA",
    DATE_FORMAT(TURMA.DATA_INICIO, '%d/%m/%Y') AS "DATA DE INÍCIO",
    DATEDIFF(CURDATE(), TURMA.DATA_INICIO) AS "DIAS DESDE O INÍCIO",
    CASE
        WHEN DATEDIFF(CURDATE(), TURMA.DATA_INICIO) <= 60 THEN "TURMA RECENTE"
        WHEN DATEDIFF(CURDATE(), TURMA.DATA_INICIO) <= 180 THEN "TURMA EM ANDAMENTO"
        ELSE "TURMA AVANÇADA"
    END AS "CLASSIFICAÇÃO"
FROM ALUNO
JOIN TURMA ON ALUNO.FK_TURMA = TURMA.IDTURMA
ORDER BY DATEDIFF(CURDATE(), TURMA.DATA_INICIO) DESC;