CREATE DATABASE EXERCICIO_02_LISTA11;

USE EXERCICIO_02_LISTA11;


CREATE TABLE FILME(
	ID_FILME INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(45) NOT NULL UNIQUE,
    DURACAO DECIMAL(4,2) NOT NULL
);

CREATE TABLE genero (
    id_genero INT NOT NULL,
    fk_filme INT NOT NULL,
	genero_filme VARCHAR(100),
    
    PRIMARY KEY (id_genero, fk_filme),
    
    CONSTRAINT ch_fk_tabela 
        FOREIGN KEY (fk_filme) 
        REFERENCES filme(id_filme)

);

CREATE TABLE PLATAFORMA(
	ID_PLATAFORMA INT PRIMARY KEY auto_increment,
    NOME VARCHAR(45)
);


CREATE TABLE SERVICO(
FK_FILME INT NOT NULL,
FK_PLATAFORMA INT NOT NULL,
STATUS_SERVICO VARCHAR(45),
PRECO_ALUGUEL DECIMAL(6,2),
PRIMARY KEY (FK_FILME,FK_PLATAFORMA),
CONSTRAINT CH_FK_FILME FOREIGN KEY (FK_FILME) REFERENCES FILME(ID_FILME),
CONSTRAINT CH_FK_PLATAFORMA FOREIGN KEY (FK_PLATAFORMA) REFERENCES PLATAFORMA(ID_PLATAFORMA)
);
