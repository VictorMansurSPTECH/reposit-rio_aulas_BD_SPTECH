CREATE DATABASE AULA8_CCOK262;

USE AULA8_CCOK262;

CREATE TABLE EMPRESA(
ID INT PRIMARY KEY AUTO_INCREMENT,
NOME VARCHAR(45),
CNPJ CHAR (14) NOT NULL
);

CREATE TABLE CARGO(
ID INT PRIMARY KEY AUTO_INCREMENT,
DESCRICAO VARCHAR(45)
);

CREATE TABLE SETOR(
ID INT PRIMARY KEY AUTO_INCREMENT,
NOME VARCHAR(45),
FK_EMPRESA INT,
CONSTRAINT CH_FK_EMPRESA FOREIGN KEY (FK_EMPRESA) REFERENCES EMPRESA(ID)
);

CREATE TABLE FUNCIONARIO(
ID INT PRIMARY KEY AUTO_INCREMENT,
NOME VARCHAR(45),
CPF CHAR(11) NOT NULL,
SALARIO DECIMAL (10,2),
FK_CHEFE INT,
FK_CARGO INT NOT NULL,
FK_SETOR INT NOT NULL,
CONSTRAINT CK_FK_CHEFE FOREIGN KEY (FK_CHEFE) REFERENCES FUNCIONARIO(ID),
CONSTRAINT CK_FK_CARGO FOREIGN KEY (FK_CARGO) REFERENCES CARGO(ID),
CONSTRAINT CK_FK_SETOR FOREIGN KEY(FK_SETOR) REFERENCES SETOR(ID)
);

