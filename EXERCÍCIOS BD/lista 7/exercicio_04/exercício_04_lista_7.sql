CREATE DATABASE EMPRESA_SETORES;
USE EMPRESA_SETORES;

CREATE TABLE SETOR (
    ID_SETOR INT PRIMARY KEY AUTO_INCREMENT,
    NOME_SETOR VARCHAR(65) NOT NULL,
    SIGLA VARCHAR(10) NOT NULL,
    FK_SETOR_SUP INT,

    CONSTRAINT FK_SETOR_SUPERIOR
        FOREIGN KEY (FK_SETOR_SUP) REFERENCES SETOR(ID_SETOR)
);

CREATE TABLE FUNCIONARIO (
    ID_FUNCIONARIO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(65) NOT NULL,
    EMAIL VARCHAR(80),
    SALARIO DECIMAL(8,2) NOT NULL,
    DATA_ADMISSAO DATE NOT NULL,
    FK_SETOR INT NOT NULL,

    CONSTRAINT FK_FUNC_SETOR
        FOREIGN KEY (FK_SETOR) REFERENCES SETOR(ID_SETOR)
);

CREATE TABLE PROJETO (
    ID_PROJETO INT PRIMARY KEY AUTO_INCREMENT,
    NOME_PROJETO VARCHAR(65) NOT NULL,
    DESCRICAO VARCHAR(255),
    DATA_INICIO DATE NOT NULL,
    DATA_PREV_TERMINO DATE,
    FK_SETOR INT NOT NULL,

    CONSTRAINT FK_PROJ_SETOR
        FOREIGN KEY (FK_SETOR) REFERENCES SETOR(ID_SETOR)
);

