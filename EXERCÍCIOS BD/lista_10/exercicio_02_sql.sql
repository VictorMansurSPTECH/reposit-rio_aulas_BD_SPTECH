CREATE DATABASE academia;
USE academia;
 
CREATE TABLE nivel_intensidade (
    idnivel_intensidade INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    descricao VARCHAR(45) NOT NULL
);
 
CREATE TABLE modalidade (
    idmodalidade INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    FK_INTENSIDADE INT NOT NULL,
    CONSTRAINT CH_FK_INTENSIDADE FOREIGN KEY (FK_INTENSIDADE)
    REFERENCES NIVEL_INTENSIDADE(IDNIVEL_INTENSIDADE)
);
 
CREATE TABLE instrutor (
    idinstrutor INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    valor_p_aula DECIMAL(8,2) NOT NULL
);
 
CREATE TABLE aluno (
    idaluno INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    dt_nasc DATE NOT NULL,
    email VARCHAR(145) NOT NULL
);
 
CREATE TABLE aula (
    idaula INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    dia_semana VARCHAR(15) NOT NULL,
    duracao_min INT NOT NULL,
    FK_INSTRUTOR INT NOT NULL,
    FK_MODALIDADE INT NOT NULL,
    CONSTRAINT CH_FK_INSTRUTOR_AULA FOREIGN KEY (FK_INSTRUTOR)
    REFERENCES INSTRUTOR(IDINSTRUTOR),
    CONSTRAINT CH_FK_MODALIDADE_AULA FOREIGN KEY (FK_MODALIDADE)
    REFERENCES MODALIDADE(IDMODALIDADE)
);
 
CREATE TABLE matricula (
    FK_ALUNO INT NOT NULL,
    FK_MODALIDADE INT NOT NULL,
    data_matricula DATE NOT NULL,
    PRIMARY KEY (FK_ALUNO, FK_MODALIDADE),
    CONSTRAINT CH_FK_ALUNO_MATRICULA FOREIGN KEY (FK_ALUNO)
    REFERENCES ALUNO(IDALUNO),
    CONSTRAINT CH_FK_MODALIDADE_MATRICULA FOREIGN KEY (FK_MODALIDADE)
    REFERENCES MODALIDADE(IDMODALIDADE)
);
 
