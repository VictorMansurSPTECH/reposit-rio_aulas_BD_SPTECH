SELECT * FROM ARTISTA;
 
SELECT
    APRESENTACAO.IDAPRESENTACAO AS "APRESENTAÇÃO",
    ARTISTA.NOME_ARTISTICO AS "ARTISTA",
    PALCO.NOME AS "PALCO",
    DATE_FORMAT(APRESENTACAO.DATA_APRESENTACAO, '%d/%m/%Y') AS "DATA",
    PARTICIPACAO.CACHE AS "CACHÊ (R$)"
FROM PARTICIPACAO
JOIN APRESENTACAO ON PARTICIPACAO.FK_APRESENTACAO = APRESENTACAO.IDAPRESENTACAO
JOIN ARTISTA ON PARTICIPACAO.FK_ARTISTA = ARTISTA.IDARTISTA
JOIN PALCO ON APRESENTACAO.FK_PALCO = PALCO.IDPALCO
ORDER BY APRESENTACAO.IDAPRESENTACAO;
 
SELECT
    ARTISTA.NOME_ARTISTICO AS "ARTISTA",
    ARTISTA.ANO_ESTREIA AS "ANO DE ESTREIA",
    COUNT(PARTICIPACAO.FK_APRESENTACAO) AS "APRESENTAÇÕES"
FROM ARTISTA
LEFT JOIN PARTICIPACAO ON PARTICIPACAO.FK_ARTISTA = ARTISTA.IDARTISTA
WHERE ARTISTA.NOME_ARTISTICO LIKE "%a%"
AND ARTISTA.ANO_ESTREIA < 2020
GROUP BY ARTISTA.IDARTISTA, ARTISTA.NOME_ARTISTICO, ARTISTA.ANO_ESTREIA;
 
SELECT
    PALCO.NOME AS "PALCO",
    COUNT(DISTINCT APRESENTACAO.IDAPRESENTACAO) AS "APRESENTAÇÕES REALIZADAS",
    IFNULL(SUM(PARTICIPACAO.CACHE), 0) AS "TOTAL DE CACHÊS (R$)"
FROM PALCO
LEFT JOIN APRESENTACAO ON APRESENTACAO.FK_PALCO = PALCO.IDPALCO
LEFT JOIN PARTICIPACAO ON PARTICIPACAO.FK_APRESENTACAO = APRESENTACAO.IDAPRESENTACAO
GROUP BY PALCO.IDPALCO, PALCO.NOME;
 
SELECT
    ARTISTA.NOME_ARTISTICO AS "ARTISTA",
    MIN(PARTICIPACAO.CACHE) AS "MENOR CACHÊ (R$)",
    MAX(PARTICIPACAO.CACHE) AS "MAIOR CACHÊ (R$)",
    ROUND(AVG(PARTICIPACAO.CACHE), 2) AS "CACHÊ MÉDIO (R$)"
FROM ARTISTA
JOIN PARTICIPACAO ON PARTICIPACAO.FK_ARTISTA = ARTISTA.IDARTISTA
GROUP BY ARTISTA.IDARTISTA, ARTISTA.NOME_ARTISTICO;
 
SELECT
    APRESENTACAO.IDAPRESENTACAO AS "APRESENTAÇÃO",
    PALCO.NOME AS "PALCO",
    COUNT(PARTICIPACAO.FK_ARTISTA) AS "QUANTIDADE DE ARTISTAS",
    SUM(PARTICIPACAO.CACHE) AS "CUSTO TOTAL (R$)"
FROM APRESENTACAO
JOIN PALCO ON APRESENTACAO.FK_PALCO = PALCO.IDPALCO
JOIN PARTICIPACAO ON PARTICIPACAO.FK_APRESENTACAO = APRESENTACAO.IDAPRESENTACAO
GROUP BY APRESENTACAO.IDAPRESENTACAO, PALCO.NOME
HAVING SUM(PARTICIPACAO.CACHE) > 5000;
 
SELECT
    PALCO.NOME AS "PALCO",
    COUNT(APRESENTACAO.IDAPRESENTACAO) AS "APRESENTAÇÕES",
    CASE
        WHEN COUNT(APRESENTACAO.IDAPRESENTACAO) = 0 THEN "Sem apresentações"
        WHEN COUNT(APRESENTACAO.IDAPRESENTACAO) <= 2 THEN "Baixa utilização"
        ELSE "Alta utilização"
    END AS "CLASSIFICAÇÃO"
FROM PALCO
LEFT JOIN APRESENTACAO ON APRESENTACAO.FK_PALCO = PALCO.IDPALCO
GROUP BY PALCO.IDPALCO, PALCO.NOME;