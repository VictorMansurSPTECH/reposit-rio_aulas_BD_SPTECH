CREATE DATABASE festival_cultural;
USE festival_cultural;
 
CREATE TABLE artista (
    idartista INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome_artistico VARCHAR(45) NOT NULL,
    pais_orig VARCHAR(45) NOT NULL,
    ano_estreia INT NOT NULL
);
 
CREATE TABLE palco (
    idpalco INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    capacidade INT NOT NULL
);
 
CREATE TABLE apresentacao (
    idapresentacao INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    data_apresentacao DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    duracao_min INT NOT NULL,
    FK_PALCO INT NOT NULL,
    CONSTRAINT CH_FK_PALCO FOREIGN KEY (FK_PALCO)
    REFERENCES PALCO(IDPALCO)
);
 
CREATE TABLE participacao (
    FK_APRESENTACAO INT NOT NULL,
    FK_ARTISTA INT NOT NULL,
    cache DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (FK_APRESENTACAO, FK_ARTISTA),
    CONSTRAINT CH_FK_APRESENTACAO FOREIGN KEY (FK_APRESENTACAO)
    REFERENCES APRESENTACAO(IDAPRESENTACAO),
    CONSTRAINT CH_FK_ARTISTA FOREIGN KEY (FK_ARTISTA)
    REFERENCES ARTISTA(IDARTISTA)
);
 
