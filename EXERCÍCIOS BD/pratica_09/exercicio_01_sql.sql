CREATE DATABASE sprint2_v3;
USE sprint2_v3;

CREATE TABLE publico_alvo (
    idpublico_alvo INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    descricao VARCHAR(45) NOT NULL
);

CREATE TABLE colecao (
    idcolecao INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    FK_PUBLICO_ALVO INT NOT NULL,
    CONSTRAINT CH_FK_PUBLICO_ALVO FOREIGN KEY (FK_PUBLICO_ALVO)
    REFERENCES PUBLICO_ALVO(IDPUBLICO_ALVO)
);

CREATE TABLE livro (
    idlivro INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    titulo VARCHAR(80) NOT NULL,
    ano_publi INT NOT NULL,
    qtd_pag INT NOT NULL,
    preco DECIMAL(8,2) NOT NULL,
    situacao VARCHAR(20) NOT NULL,
    FK_COLECAO INT NOT NULL,
    CONSTRAINT CH_FK_COLECAO FOREIGN KEY (FK_COLECAO)
    REFERENCES COLECAO(IDCOLECAO)
);

