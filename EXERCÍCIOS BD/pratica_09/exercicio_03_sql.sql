
USE sprint2_v3;

CREATE TABLE curso (
    idcurso INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome_curso VARCHAR(45) NOT NULL,
    carga_horas INT NOT NULL
);

CREATE TABLE turno (
    idturno INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome_turno VARCHAR(45) NOT NULL
);

CREATE TABLE status_matricula (
    idstatus INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    descricao VARCHAR(45) NOT NULL
);

CREATE TABLE turma (
    idturma INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    codigo VARCHAR(20) NOT NULL,
    data_inicio DATE NOT NULL,
    FK_CURSO INT NOT NULL,
    FK_TURNO INT NOT NULL,
    CONSTRAINT CH_FK_CURSO FOREIGN KEY (FK_CURSO)
    REFERENCES CURSO(IDCURSO),
    CONSTRAINT CH_FK_TURNO FOREIGN KEY (FK_TURNO)
    REFERENCES TURNO(IDTURNO)
);

CREATE TABLE aluno (
    idaluno INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    RA VARCHAR(20) NOT NULL,
    nome_aluno VARCHAR(45) NOT NULL,
    email VARCHAR(145) NOT NULL,
    data_nasc DATE NOT NULL,
    FK_TURMA INT NOT NULL,
    FK_STATUS INT NOT NULL,
    CONSTRAINT CH_FK_TURMA FOREIGN KEY (FK_TURMA)
    REFERENCES TURMA(IDTURMA),
    CONSTRAINT CH_FK_STATUS FOREIGN KEY (FK_STATUS)
    REFERENCES STATUS_MATRICULA(IDSTATUS)
);

