CREATE DATABASE DEPARTAMENTO2;
USE DEPARTAMENTO2;

CREATE TABLE DEPARTAMENTO (
    ID_DEPARTAMENTO INT PRIMARY KEY AUTO_INCREMENT,
    NOME_DEPARTAMENTO VARCHAR(65) NOT NULL,
    ANDAR VARCHAR(25)
);

CREATE TABLE FUNCIONARIO (
    ID_FUNCIONARIO INT PRIMARY KEY AUTO_INCREMENT,
    SALARIO DECIMAL(8,2) NOT NULL,
    NOME VARCHAR(45) NOT NULL,
    EMAIL VARCHAR(80),
    DATA_EMI DATE,
    FK_DEPARTAMENTO INT NOT NULL,
    FK_SUPERVISOR INT,
    
    CONSTRAINT FK_FUNC_DEPARTAMENTO 
        FOREIGN KEY (FK_DEPARTAMENTO) REFERENCES DEPARTAMENTO(ID_DEPARTAMENTO),
        
    CONSTRAINT FK_FUNC_SUPERVISOR 
        FOREIGN KEY (FK_SUPERVISOR) REFERENCES FUNCIONARIO(ID_FUNCIONARIO)
);

