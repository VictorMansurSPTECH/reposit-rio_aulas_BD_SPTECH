
USE sprint2_v3;

CREATE TABLE area_atuacao (
    idarea_atuacao INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL
);

CREATE TABLE equipe (
    idequipe INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome_equipe VARCHAR(45) NOT NULL,
    FK_AREA_ATUACAO INT NOT NULL,
    CONSTRAINT CH_FK_AREA_ATUACAO FOREIGN KEY (FK_AREA_ATUACAO)
    REFERENCES AREA_ATUACAO(IDAREA_ATUACAO)
);

CREATE TABLE funcionario (
    idfuncionario INT PRIMARY KEY NOT NULL AUTO_INCREMENT,
    nome VARCHAR(45) NOT NULL,
    email VARCHAR(145) NOT NULL,
    data_admin DATE NOT NULL,
    salario DECIMAL(10,2) NOT NULL,
    FK_EQUIPE INT NOT NULL,
    FK_MENTOR INT NULL,
    CONSTRAINT CH_FK_EQUIPE FOREIGN KEY (FK_EQUIPE)
    REFERENCES EQUIPE(IDEQUIPE),
    CONSTRAINT CH_FK_MENTOR FOREIGN KEY (FK_MENTOR)
    REFERENCES FUNCIONARIO(IDFUNCIONARIO)
);

