SELECT * FROM LIVRO;

SELECT
    LIVRO.TITULO AS "TÍTULO DO LIVRO",
    COLECAO.NOME AS "COLEÇÃO",
    PUBLICO_ALVO.DESCRICAO AS "PÚBLICO-ALVO"
FROM LIVRO
JOIN COLECAO ON LIVRO.FK_COLECAO = COLECAO.IDCOLECAO
JOIN PUBLICO_ALVO ON COLECAO.FK_PUBLICO_ALVO = PUBLICO_ALVO.IDPUBLICO_ALVO;

SELECT DISTINCT
    COLECAO.NOME AS "COLEÇÃO"
FROM COLECAO
JOIN LIVRO ON LIVRO.FK_COLECAO = COLECAO.IDCOLECAO
JOIN PUBLICO_ALVO ON COLECAO.FK_PUBLICO_ALVO = PUBLICO_ALVO.IDPUBLICO_ALVO
WHERE PUBLICO_ALVO.DESCRICAO = "Infantil";

SELECT
    LIVRO.TITULO AS "TÍTULO DO LIVRO",
    LIVRO.ANO_PUBLI AS "ANO DE PUBLICAÇÃO"
FROM LIVRO
WHERE LIVRO.ANO_PUBLI > 2010
ORDER BY LIVRO.ANO_PUBLI DESC
LIMIT 3;

SELECT
    LIVRO.TITULO AS "TÍTULO DO LIVRO",
    LIVRO.PRECO AS "PREÇO"
FROM LIVRO
WHERE LIVRO.PRECO BETWEEN 30 AND 50
ORDER BY LIVRO.PRECO ASC;

SELECT
    LIVRO.TITULO AS "TÍTULO DO LIVRO",
    LIVRO.QTD_PAG AS "PÁGINAS",
    CASE
        WHEN LIVRO.QTD_PAG <= 200 THEN "CURTO"
        WHEN LIVRO.QTD_PAG BETWEEN 201 AND 400 THEN "MÉDIO"
        ELSE "LONGO"
    END AS "CLASSIFICAÇÃO"
FROM LIVRO
ORDER BY LIVRO.QTD_PAG ASC;

