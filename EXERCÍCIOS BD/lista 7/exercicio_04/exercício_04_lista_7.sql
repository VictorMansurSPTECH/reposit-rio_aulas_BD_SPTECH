SELECT
    F.NOME AS "FUNCIONÁRIO",
    S.NOME_SETOR AS "SETOR"
FROM FUNCIONARIO AS F JOIN SETOR AS S ON F.FK_SETOR = S.ID_SETOR;

SELECT
    P.NOME_PROJETO AS "PROJETO",
    S.NOME_SETOR AS "SETOR RESPONSÁVEL"
FROM PROJETO AS P JOIN SETOR AS S ON P.FK_SETOR = S.ID_SETOR;

SELECT
    F.NOME AS "FUNCIONÁRIO",
    F.DATA_ADMISSAO AS "DATA DE ADMISSÃO",
    S.NOME_SETOR AS "SETOR"
FROM FUNCIONARIO AS F JOIN SETOR AS S ON F.FK_SETOR = S.ID_SETOR
WHERE F.DATA_ADMISSAO > '2019-01-01';

SELECT
    SUB.NOME_SETOR AS "SETOR SUBORDINADO",
    SUP.NOME_SETOR AS "SETOR SUPERIOR"
FROM SETOR AS SUB JOIN SETOR AS SUP ON SUB.FK_SETOR_SUP = SUP.ID_SETOR;

SELECT
    SUB.NOME_SETOR AS "SETOR",
    SUP.NOME_SETOR AS "SETOR SUPERIOR"
FROM SETOR AS SUB LEFT JOIN SETOR AS SUP ON SUB.FK_SETOR_SUP = SUP.ID_SETOR;

SELECT
    SUB.NOME_SETOR AS "SETOR SUBORDINADO"
FROM SETOR AS SUB
WHERE SUB.FK_SETOR_SUP = 1;

SELECT
    S.NOME_SETOR AS "SETOR",
    F.NOME AS "FUNCIONÁRIO"
FROM SETOR AS S LEFT JOIN FUNCIONARIO AS F ON S.ID_SETOR = F.FK_SETOR;

SELECT
    F.NOME AS "FUNCIONÁRIO",
    F.SALARIO AS "SALÁRIO",
    S.NOME_SETOR AS "SETOR",
    CASE
        WHEN F.SALARIO <= 5000 THEN "SALÁRIO BAIXO"
        WHEN F.SALARIO > 5000 AND F.SALARIO <= 10000 THEN "SALÁRIO MÉDIO"
        ELSE "SALÁRIO ALTO"
    END AS "CLASSIFICAÇÃO SALARIAL"
FROM FUNCIONARIO AS F JOIN SETOR AS S ON F.FK_SETOR = S.ID_SETOR
ORDER BY F.SALARIO ASC;

